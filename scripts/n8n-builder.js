'use strict';
/**
 * Tiny DSL for producing n8n workflow JSON from version-controlled sources.
 * Code nodes are assembled from src/nodes/** and src/lib/** so the code that is unit-tested
 * is byte-for-byte the code that runs inside n8n.
 */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const ROOT = path.resolve(__dirname, '..');
const LIB_DIR = path.join(ROOT, 'src', 'lib');
const NODES_DIR = path.join(ROOT, 'src', 'nodes');

const CREDENTIALS = {
  postgres: { postgres: { id: 'pwPostgres000001', name: 'PlacidWay Postgres' } },
  llm: { httpHeaderAuth: { id: 'pwLlmApiKey00001', name: 'LLM API key (Bearer)' } },
  facebook: { httpQueryAuth: { id: 'pwFbPageToken001', name: 'Facebook Page token' } },
  telegram: { telegramApi: { id: 'pwTelegramBot001', name: 'Telegram alerts bot' } },
};

function libDeps(name, seen = new Set(), order = []) {
  if (seen.has(name)) return order;
  seen.add(name);
  const src = fs.readFileSync(path.join(LIB_DIR, `${name}.js`), 'utf8');
  for (const m of src.matchAll(/require\('\.\/(\w+)'\)/g)) libDeps(m[1], seen, order);
  order.push(name);
  return order;
}

function bundle(nodeFile) {
  const rel = path.relative(ROOT, path.join(NODES_DIR, nodeFile));
  let src = fs.readFileSync(path.join(NODES_DIR, nodeFile), 'utf8');
  const libs = [];
  const seen = new Set();
  for (const m of src.matchAll(/require\('(?:\.\.\/)+lib\/(\w+)'\)/g)) libDeps(m[1], seen, libs);
  src = src.replace(/require\('(?:\.\.\/)+lib\/(\w+)'\)/g, '__lib_$1');
  const parts = [
    `// GENERATED by scripts/build-workflows.js from ${rel} (+ src/lib). Edit the sources and run "npm run build".`,
    '// The inlined libraries below are unit-tested in test/*.test.js.',
  ];
  for (const lib of libs) {
    let code = fs.readFileSync(path.join(LIB_DIR, `${lib}.js`), 'utf8');
    code = code.replace(/^'use strict';\n/, '').replace(/require\('\.\/(\w+)'\)/g, '__lib_$1');
    parts.push(`// ---------- src/lib/${lib}.js ----------\nconst __lib_${lib} = (() => {\n  const module = { exports: {} };\n${code}\n  return module.exports;\n})();`);
  }
  parts.push(`// ---------- ${rel} ----------\n${src.trim()}`);
  return parts.join('\n\n');
}

function stableId(seed) {
  const h = crypto.createHash('sha1').update(seed).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

class WorkflowBuilder {
  constructor({ id, name, settings, tags }) {
    this.wf = { id, name, nodes: [], connections: {}, settings: settings || {}, pinData: {}, active: false, meta: { templateCredsSetupCompleted: false }, tags: tags || [] };
    this.names = new Set();
  }

  add(node) {
    if (this.names.has(node.name)) throw new Error(`duplicate node name ${node.name}`);
    this.names.add(node.name);
    this.wf.nodes.push({ id: stableId(`${this.wf.id}:${node.name}`), ...node });
    return node.name;
  }

  // -- node helpers ---------------------------------------------------------
  code(name, file, position, extra = {}) {
    return this.add({ name, type: 'n8n-nodes-base.code', typeVersion: 2, position, parameters: { jsCode: bundle(file) }, ...extra });
  }

  http(name, position, parameters, extra = {}) {
    return this.add({ name, type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2, position, parameters, ...extra });
  }

  pg(name, query, position, { payload = true, ...extra } = {}) {
    const parameters = { operation: 'executeQuery', query, options: payload ? { queryReplacement: '={{ $json.db_payload_b64 }}' } : {} };
    if (typeof payload === 'string') parameters.options.queryReplacement = payload;
    return this.add({ name, type: 'n8n-nodes-base.postgres', typeVersion: 2.5, position, parameters, credentials: CREDENTIALS.postgres, ...extra });
  }

  iff(name, expression, position, extra = {}) {
    return this.add({
      name, type: 'n8n-nodes-base.if', typeVersion: 2.2, position, ...extra,
      parameters: {
        conditions: {
          options: { caseSensitive: true, leftValue: '', typeValidation: 'loose', version: 2 },
          conditions: [{ id: stableId(`${name}:cond`), leftValue: `={{ ${expression} }}`, rightValue: '', operator: { type: 'boolean', operation: 'true', singleValue: true } }],
          combinator: 'and',
        },
        looseTypeValidation: true,
        options: {},
      },
    });
  }

  delay(name, secondsExpr, position) {
    return this.add({ name, type: 'n8n-nodes-base.wait', typeVersion: 1.1, position, webhookId: stableId(`${name}:wh`), parameters: { amount: `={{ ${secondsExpr} }}`, unit: 'seconds' } });
  }

  telegram(name, chatIdExpr, textExpr, position, extra = {}) {
    return this.add({
      name, type: 'n8n-nodes-base.telegram', typeVersion: 1.2, position, webhookId: stableId(`${name}:wh`),
      parameters: { chatId: `={{ ${chatIdExpr} }}`, text: `={{ ${textExpr} }}`, additionalFields: { appendAttribution: false, parse_mode: 'HTML', disable_web_page_preview: true } },
      credentials: CREDENTIALS.telegram, ...extra,
    });
  }

  sticky(name, content, position, width, height, color) {
    return this.add({ name, type: 'n8n-nodes-base.stickyNote', typeVersion: 1, position, parameters: { content, width, height, color: color || 7 } });
  }

  raw(node) { return this.add(node); }

  // -- connections ----------------------------------------------------------
  connect(from, to, output = 0, input = 0) {
    if (!this.names.has(from)) throw new Error(`unknown node ${from}`);
    if (!this.names.has(to)) throw new Error(`unknown node ${to}`);
    const c = (this.wf.connections[from] = this.wf.connections[from] || { main: [] });
    while (c.main.length <= output) c.main.push([]);
    c.main[output].push({ node: to, type: 'main', index: input });
  }

  chain(...names) {
    for (let i = 0; i < names.length - 1; i++) this.connect(names[i], names[i + 1]);
  }

  build() {
    // fill empty output arrays so n8n renders unconnected outputs correctly
    return JSON.parse(JSON.stringify(this.wf));
  }
}

module.exports = { WorkflowBuilder, CREDENTIALS, bundle, stableId };
